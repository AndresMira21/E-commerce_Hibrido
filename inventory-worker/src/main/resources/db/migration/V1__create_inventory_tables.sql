-- Esquema inicial: solo estructura, sin productos de prueba ni operaciones destructivas.
CREATE TABLE inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(255) NOT NULL,
    available_quantity INTEGER NOT NULL,
    version BIGINT NOT NULL,
    CONSTRAINT uk_inventory_items_product_name UNIQUE (product_name),
    CONSTRAINT ck_inventory_items_available_quantity CHECK (available_quantity >= 0)
);

CREATE TABLE stock_reservations (
    order_id UUID PRIMARY KEY,
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_stock_reservations_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_reservations_status CHECK (status IN ('STOCK_RESERVED', 'OUT_OF_STOCK'))
);
